/**
 * Phase 14 SEO build step.
 *
 * Vite plugin (no dependency added) that turns the resolved SEO configuration
 * into the two files a crawler actually reads:
 *
 *   robots.txt    — always emitted, matching the current indexing policy;
 *   sitemap.xml   — emitted **only** when a confirmed production origin exists
 *                   and indexing is enabled, because a sitemap is a list of
 *                   absolute URLs and inventing them is worse than omitting it.
 *
 * The same policy is applied to `index.html` in `transformIndexHtml`, so the
 * markup that arrives before JavaScript runs agrees with the runtime tags and
 * with `robots.txt`. There is exactly one source for the decision:
 * `resolveSeoConfig` in `src/config/site-config.ts`, shared with the client.
 *
 * Route facts come from `src/config/routes.ts` and `src/config/metadata.ts`, so
 * a page cannot exist without appearing (or deliberately not appearing) in the
 * sitemap.
 */

import type { Plugin } from "vite";

import { SITEMAP_PATHS } from "../src/config/metadata";
import { absoluteUrl, resolveSeoConfig, type SeoConfig } from "../src/config/site-config";

const GENERATED = "Generated by the Phase 14 SEO configuration (website/vite/seo-plugin.ts).";

/** The meta tag in `index.html` this plugin owns. */
const ROBOTS_TAG = /<meta\s+name="robots"[^>]*>/;

const NON_INDEXABLE_NOTE = [
  "# This build is NOT configured for public indexing.",
  "# That is the default: the site has no confirmed production domain yet,",
  "# and a development or preview deployment must not be indexed.",
  "#",
  "# To enable indexing for a confirmed production launch, set both",
  "#   VITE_SITE_URL=https://<confirmed-production-domain>",
  "#   VITE_SITE_INDEXABLE=true",
  "# and rebuild. This file, the page-level robots metadata, and sitemap.xml",
  "# are then generated from that single configuration.",
];

const INDEXABLE_NOTE = [
  "# This build IS configured for public indexing.",
  "# Generated from VITE_SITE_URL + VITE_SITE_INDEXABLE; do not edit by hand.",
];

/**
 * `robots.txt` body.
 *
 * The non-indexable branch uses `Disallow: /` rather than relying on the
 * page-level `noindex` alone, so a crawler that does not execute JavaScript
 * still stays out of an unlaunched deployment. The indexable branch allows
 * everything: there are no private paths on this site, and a broad `Disallow`
 * would also block the assets a crawler needs to render a page.
 */
export function robotsTxt(config: SeoConfig): string {
  const lines = [`# Nexora website — robots.txt. ${GENERATED}`, ""];
  if (config.indexable && config.url !== null) {
    lines.push(...INDEXABLE_NOTE, "", "User-agent: *", "Allow: /", "");
    lines.push(`Sitemap: ${config.url}/sitemap.xml`);
  } else {
    lines.push(...NON_INDEXABLE_NOTE, "", "User-agent: *", "Disallow: /");
    lines.push(
      "",
      "# A robots directive is crawler guidance, not access control. It does not",
      "# make a deployment private; use host-level authentication for that.",
    );
  }
  return `${lines.join("\n")}\n`;
}

/**
 * `sitemap.xml` body, or `null` when there is no confirmed origin.
 *
 * Only `<loc>` is emitted. `lastmod`, `changefreq` and `priority` are all
 * optional, and every value for them here would be invented: the site has no
 * per-page modification tracking and no reason to claim an update cadence.
 */
export function sitemapXml(config: SeoConfig): string | null {
  if (!config.indexable || config.url === null) return null;
  // `SITEMAP_PATHS` is already filtered by `PAGE_METADATA[...].indexable`.
  const urls = SITEMAP_PATHS.map((path) => absoluteUrl(config.url, path)).filter(
    (url): url is string => url !== null,
  );
  const body = urls.map((url) => `  <url>\n    <loc>${escapeXml(url)}</loc>\n  </url>`).join("\n");
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    "<!-- Nexora website sitemap. " + GENERATED + " -->",
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    body,
    "</urlset>",
    "",
  ].join("\n");
}

function escapeXml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

/** A crawl file response, or `null` if the path is not one this plugin owns. */
interface CrawlFile {
  status: number;
  contentType: string;
  body: string;
}

/**
 * Resolves `/robots.txt` and `/sitemap.xml` from the build configuration.
 *
 * Both servers below use this, so the answer is identical whether the files are
 * read from memory (dev) or from `dist/` (preview) — and, critically, a missing
 * sitemap is a `404` with a plain-text explanation rather than the SPA shell.
 */
function resolveCrawlFile(config: SeoConfig, url: string): CrawlFile | null {
  const path = url.split("?")[0];
  if (path === "/robots.txt") {
    return { status: 200, contentType: "text/plain; charset=utf-8", body: robotsTxt(config) };
  }
  if (path === "/sitemap.xml") {
    const sitemap = sitemapXml(config);
    if (sitemap === null) {
      return {
        status: 404,
        contentType: "text/plain; charset=utf-8",
        body: "No sitemap: no confirmed production domain is configured.\n",
      };
    }
    return { status: 200, contentType: "application/xml; charset=utf-8", body: sitemap };
  }
  return null;
}

export function seoPlugin(env: Record<string, string | undefined>): Plugin {
  const config = resolveSeoConfig(env);

  return {
    name: "nexora-seo",

    configResolved(resolved) {
      for (const warning of config.warnings) resolved.logger.warn(`[seo] ${warning}`);
      resolved.logger.info(
        config.indexable && config.url
          ? `[seo] indexing enabled for ${config.url}`
          : "[seo] indexing disabled — no confirmed production origin is configured",
      );
    },

    transformIndexHtml(html) {
      if (!ROBOTS_TAG.test(html)) {
        throw new Error(
          "[seo] index.html no longer contains a <meta name=\"robots\"> tag; the SEO plugin cannot set the indexing policy.",
        );
      }
      const directive = config.indexable ? "index, follow" : "noindex, nofollow";
      let out = html.replace(ROBOTS_TAG, `<meta name="robots" content="${directive}" />`);
      // The home route's canonical is stable enough to state in the markup;
      // every other route's is written by `usePageMetadata` on navigation.
      const home = absoluteUrl(config.url, "/");
      if (home !== null) {
        out = out.replace("</head>", `    <link rel="canonical" href="${home}" />\n  </head>`);
      }
      return out;
    },

    generateBundle() {
      this.emitFile({ type: "asset", fileName: "robots.txt", source: robotsTxt(config) });
      const sitemap = sitemapXml(config);
      if (sitemap !== null) {
        this.emitFile({ type: "asset", fileName: "sitemap.xml", source: sitemap });
      }
    },

    // The dev server has no build output, so these two paths are answered from
    // the same configuration that generated the files.
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        // `req.url` is present on a real Node request but is absent from the
        // Connect typings this package resolves without @types/node.
        const file = resolveCrawlFile(config, (req as { url?: string }).url ?? "");
        if (file === null) return next();
        res.statusCode = file.status;
        res.setHeader("Content-Type", file.contentType);
        res.end(file.body);
      });
    },

    /**
     * The preview server is the only place a built bundle is served locally, and
     * it applies an SPA fallback to *every* unknown path. Without this hook
     * `/sitemap.xml` answered `200 text/html` — the app shell — whenever no
     * sitemap had been emitted, which contradicts `robots.txt` and misleads
     * anyone checking launch readiness.
     *
     * This serves the crawl files with the correct status and type locally. It
     * does **not** configure a real host: a production server must exclude
     * `/robots.txt`, `/sitemap.xml` and `/assets/*` from its own SPA rewrite,
     * which is deployment configuration and remains documented in the README.
     */
    configurePreviewServer(server) {
      server.middlewares.use((req, res, next) => {
        // `req.url` is present on a real Node request but is absent from the
        // Connect typings this package resolves without @types/node.
        const file = resolveCrawlFile(config, (req as { url?: string }).url ?? "");
        if (file === null) return next();
        res.statusCode = file.status;
        res.setHeader("Content-Type", file.contentType);
        res.end(file.body);
      });
    },
  };
}
