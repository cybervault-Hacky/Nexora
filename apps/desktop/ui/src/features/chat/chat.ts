export const MAX_MESSAGE_LENGTH = 32_000;
export const WARN_MESSAGE_LENGTH = 4_000;

export type ChatRole = "user" | "assistant";

/** `scaffold` marks text written by the shell, never by a model. */
export type AssistantKind = "scaffold";

export interface ChatMessage {
  id: string;
  role: ChatRole;
  content: string;
  kind?: AssistantKind;
  createdAt: number;
}

export type ComposerErrorCode = "empty" | "too_long";

export interface ComposerError {
  code: ComposerErrorCode;
  message: string;
}

export type SubmitOutcome =
  | { ok: true; messages: ChatMessage[] }
  | { ok: false; messages: ChatMessage[]; error: ComposerError };

interface MessageContext {
  createId: () => string;
  now: () => number;
}

const EMPTY_ERROR: ComposerError = {
  code: "empty",
  message: "Enter a message before sending.",
};

const TOO_LONG_ERROR: ComposerError = {
  code: "too_long",
  message: `Messages are limited to ${MAX_MESSAGE_LENGTH.toLocaleString(
    "en-US",
  )} characters.`,
};

/**
 * The single scaffold reply. It is deliberately written by the interface and
 * labelled as such, so the first build never implies that inference works.
 */
export const SCAFFOLD_REPLY = [
  "This is a scaffold response from the Nexora desktop shell. No local model is connected yet, so this text was written by the interface — not generated by AI.",
  "Your message was kept in this session only. When the local inference engine is added in a later phase, a streamed model reply will appear here with Stop, context, and verification controls.",
].join("\n\n");

export function validateDraft(draft: string):
  | { ok: true; text: string }
  | { ok: false; error: ComposerError } {
  const text = draft.replace(/\r\n/g, "\n").trim();

  if (text.length === 0) {
    return { ok: false, error: EMPTY_ERROR };
  }

  if (text.length > MAX_MESSAGE_LENGTH) {
    return { ok: false, error: TOO_LONG_ERROR };
  }

  return { ok: true, text };
}

export function createScaffoldReply(context: MessageContext): ChatMessage {
  return {
    id: context.createId(),
    role: "assistant",
    kind: "scaffold",
    content: SCAFFOLD_REPLY,
    createdAt: context.now(),
  };
}

/**
 * Appends the user turn and the labelled scaffold reply, or returns a composer
 * error without mutating the conversation.
 */
export function submitDraft(
  messages: readonly ChatMessage[],
  draft: string,
  context: MessageContext,
): SubmitOutcome {
  const validation = validateDraft(draft);

  if (!validation.ok) {
    return {
      ok: false,
      messages: [...messages],
      error: validation.error,
    };
  }

  const userMessage: ChatMessage = {
    id: context.createId(),
    role: "user",
    content: validation.text,
    createdAt: context.now(),
  };

  return {
    ok: true,
    messages: [
      ...messages,
      userMessage,
      createScaffoldReply(context),
    ],
  };
}
