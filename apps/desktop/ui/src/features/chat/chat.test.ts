import { describe, expect, it } from "vitest";
import {
  MAX_MESSAGE_LENGTH,
  SCAFFOLD_REPLY,
  submitDraft,
  validateDraft,
  type ChatMessage,
} from "./chat";

function context() {
  let nextId = 0;
  let nextTime = 1_000;

  return {
    createId: () => `id-${++nextId}`,
    now: () => nextTime++,
  };
}

describe("validateDraft", () => {
  it("rejects an empty draft", () => {
    const result = validateDraft("   \n\t ");

    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error.code).toBe("empty");
    }
  });

  it("trims surrounding whitespace and normalises CRLF", () => {
    const result = validateDraft("  fix the build\r\nplease  ");

    expect(result).toEqual({ ok: true, text: "fix the build\nplease" });
  });

  it("accepts a message at the length limit", () => {
    const result = validateDraft("a".repeat(MAX_MESSAGE_LENGTH));

    expect(result.ok).toBe(true);
  });

  it("rejects a message over the length limit", () => {
    const result = validateDraft("a".repeat(MAX_MESSAGE_LENGTH + 1));

    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error.code).toBe("too_long");
    }
  });
});

describe("submitDraft", () => {
  it("does not add messages for an empty draft", () => {
    const messages: ChatMessage[] = [];
    const outcome = submitDraft(messages, "  ", context());

    expect(outcome.ok).toBe(false);
    expect(outcome.messages).toHaveLength(0);
  });

  it("adds the user turn and a labelled scaffold reply", () => {
    const outcome = submitDraft([], "build a landing page", context());

    expect(outcome.ok).toBe(true);
    expect(outcome.messages).toHaveLength(2);

    const [user, assistant] = outcome.messages;
    expect(user).toMatchObject({
      role: "user",
      content: "build a landing page",
    });
    expect(user?.id).not.toBe(assistant?.id);
    expect(assistant).toMatchObject({
      role: "assistant",
      kind: "scaffold",
      content: SCAFFOLD_REPLY,
    });
  });

  it("keeps existing messages in order", () => {
    const existing: ChatMessage = {
      id: "existing",
      role: "user",
      content: "hello",
      createdAt: 1,
    };

    const outcome = submitDraft([existing], "second", context());

    expect(outcome.messages.map((message) => message.id)).toEqual([
      "existing",
      "id-1",
      "id-2",
    ]);
  });

  it("never marks a scaffold reply as model output", () => {
    const outcome = submitDraft([], "hello", context());
    const assistant = outcome.messages.at(-1);

    expect(assistant?.kind).toBe("scaffold");
    expect(assistant?.content).toContain("not generated by AI");
  });
});
